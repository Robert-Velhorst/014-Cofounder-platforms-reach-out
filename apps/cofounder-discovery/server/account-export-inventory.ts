export function accountExportPlan(registry: Record<string, unknown> = schema) {
  const entries = Object.entries(registry).filter(([, value]) =>
    is(value, Table)
  );
  if (entries.length !== Object.keys(accountExportInventory).length)
    throw new Error("account_export_schema_review_required");
  return entries.map(([key, value]) => {
    const rule = accountExportInventory[key];
    if (!rule) throw new Error("account_export_schema_review_required");
    const table = value as AnyMySqlTable,
      columns = getTableColumns(table);
    const reviewed = [
      ...rule.fields,
      ...Object.keys(rule.excludedFields),
    ].sort();
    if (
      JSON.stringify(Object.keys(columns).sort()) !== JSON.stringify(reviewed)
    )
      throw new Error("account_export_field_review_required");
    const projection = Object.fromEntries(
      rule.fields.map(field => [field, columns[field]])
    );
    return { key, rule, table, columns, projection };
  });
}
